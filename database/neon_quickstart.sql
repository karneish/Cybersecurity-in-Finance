-- 3. TABLES, INDEXES, FUNCTIONS AND SEED DATA
-- ---------------------------------------------------------------------------
-- Do NOT paste SQL from here by hand on an empty database unless you intend to
-- bypass the app's own migration path. Instead use one of:
--
--   (a) Automatic (recommended): deploy to Render. start.sh runs
--       database/migrate_and_seed.py, which applies database/init.sql,
--       all twelve migrations in database/migrations/, and the seed data.
--
--   (b) Manual full snapshot: run the entire contents of
--       database/neon_setup.sql (generated by database/generate_neon_setup.py).
--       That file is schema + migrations 001-012 + seed in one paste. It is
--       written for a ONE-TIME run on an empty database: schemas use
--       IF NOT EXISTS, but the core seed inserts are plain INSERTs, so
--       re-running it on a seeded database will fail on duplicate keys.
--
--   (c) Just the schema, no seed: run these in order —
--         database/init.sql
--         database/migrations/001_create_auth_tables.sql
--         database/migrations/002_create_asset_tables.sql
--         database/migrations/003_create_vuln_tables.sql
