-- ============================================================================
-- CyberRisk Quantifier — NeonDB quickstart
-- ============================================================================
--
-- READ THIS FIRST: you probably do not need to run anything.
--
-- The backend creates and populates its own database. On every boot
-- deploy/render/start.sh runs `database/migrate_and_seed.py`, which applies
-- database/init.sql, then migrations 001-012, then the seed data. It is
-- idempotent, so it is safe on every deploy and it is how your Render
-- database gets built. You only need a connection string.
--
-- So the normal flow is:
--   1. Neon Console -> create a project (free) -> it gives you a database
--   2. Copy the POOLED connection string
--   3. Paste it into Render as DATABASE_URL when the Blueprint prompts
--   Done. The schema and seed appear by themselves on first deploy.
--
-- This file is for the cases where you want to do it by hand, or want to
-- inspect what should exist. Sections are ordered by how likely you are to
-- need them.
--
-- ---------------------------------------------------------------------------
-- 1. CREATE THE DATABASE
-- ---------------------------------------------------------------------------
-- Neon already creates a database named `neondb` when you create a project,
-- and the connection string Neon hands you points at it. That is the path to
-- take: nothing to do, and nothing to change in the connection string.
--
-- `CREATE DATABASE` only if you want a second, differently named database.
-- Run this while connected to an existing database (Neon Console -> SQL Editor
-- opens on `neondb` by default):
--
--   CREATE DATABASE cyberrisk;
--
-- If you do that, your connection string must end in `/cyberrisk` instead of
-- `/neondb`. Everything after this point is unchanged.
--
-- You cannot run CREATE DATABASE from inside a transaction block, and you
-- cannot drop the database you are currently connected to.

-- Uncomment to create an additional database:
-- CREATE DATABASE cyberrisk;

-- To see what already exists:
--   SELECT datname FROM pg_database WHERE datistemplate = false ORDER BY datname;


