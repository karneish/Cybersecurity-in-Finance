-- ---------------------------------------------------------------------------
-- 4. VERIFY  (paste after deploying — everything should return rows)
-- ---------------------------------------------------------------------------

-- 4a. All seven schemas exist. Expect 7 rows.
SELECT nspname AS schema
FROM pg_namespace
WHERE nspname IN ('auth','asset','vuln','control','risk','investment','gov')
ORDER BY nspname;

-- 4b. Table count per schema. Expect a row for each of the seven above.
--     `public.data_sources` is created outside the named schemas by migration
--     009, so add a query for it too if you want a complete picture.
SELECT table_schema, COUNT(*) AS tables
FROM information_schema.tables
WHERE table_schema IN ('auth','asset','vuln','control','risk','investment','gov')
GROUP BY table_schema
ORDER BY table_schema;

-- 4c. Demo logins. Expect 3 rows, all with role CISO / ANALYST / ANALYST.
--     Password for all three: Scro@2026!
SELECT username, email, role, is_active FROM auth.users ORDER BY role DESC, username;

-- 4d. Seeded core data. Expect: assets 12, controls 10, vulnerabilities 15,
--     agencies 3, data sources 7.
SELECT 'assets'        AS entity, COUNT(*) FROM asset.assets
UNION ALL SELECT 'security_controls',  COUNT(*) FROM control.security_controls
UNION ALL SELECT 'vulnerabilities',    COUNT(*) FROM vuln.vulnerabilities
UNION ALL SELECT 'agencies',          COUNT(*) FROM gov.agencies
UNION ALL SELECT 'data_sources',      COUNT(*) FROM public.data_sources
ORDER BY entity;

-- 4e. Risk calculations were generated for every asset. Expect assets = risks.
SELECT (SELECT COUNT(*) FROM asset.assets)           AS assets,
       (SELECT COUNT(*) FROM risk.risk_calculations) AS risk_calculations,
       (SELECT COUNT(*) FROM risk.risk_snapshots)    AS snapshots;

-- 4f. The audit chain is intact: every row links to a previous one.
--     Expect broken_links = 0.
SELECT COUNT(*) AS broken_links
FROM risk.audit_entries AS c
WHERE c.prev_hash IS NOT NULL
  AND NOT EXISTS (SELECT 1 FROM risk.audit_entries p WHERE p.data_hash = c.prev_hash);


-- ---------------------------------------------------------------------------
-- 5. THINGS THAT COMMONLY GO WRONG
-- ---------------------------------------------------------------------------
--
-- "relation ... does not exist" from the app, but the tables are there
--   -> The connection string's search_path is not reaching your schemas. The
--      services always qualify names (auth.users, asset.assets), so this means
--      the app is pointed at a different database than the one you inspected.
--      Check the database name at the end of DATABASE_URL.
--
-- SSL / "server closed the connection unexpectedly"
--   -> Use the POOLED (-pooler) connection string, and keep
--      `?sslmode=require`. Neon requires TLS. start.sh appends sslmode=require
--      automatically if it is missing, and works with either the pooled or the
--      direct host.
--
-- "too many connections"
--   -> Neon caps connections per database. Keep DB_POOL_SIZE=2 and
--      DB_MAX_OVERFLOW=2 in render.yaml. Eight services share one database, so
--      the defaults of 10+20 would try to open ~240 connections.
--
-- Everything times out from Render
--   -> Neon free projects pause after a period of inactivity and resume on the
--      next connection, which can take a few seconds. start.sh already waits up
--      to ~5 minutes for Postgres before continuing, so a cold Neon simply
--      delays boot rather than failing the deploy.